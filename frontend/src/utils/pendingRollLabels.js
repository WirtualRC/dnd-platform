// Сокет-подтверждение "мой бросок долетел" не содержит человекочитаемого
// названия (бэкенд хранит только formula/result/breakdown, не "Проверка:
// Сила") — сопоставляем по порядку отправки. Не идеально при частых
// параллельных бросках одного игрока, но для личного стола достаточно.
// Отдельный модуль специально, чтобы utils/roll.js и store/useRoomStore.js
// могли оба его использовать, не импортируя друг друга по кругу.
const pending = [];

export function pushPendingRollLabel(label) {
  pending.push(label);
}

// null, если очередь пуста — так вызывающий может отличить "это бросок из
// листа персонажа" (был лейбл) от "это бросок из собственного кубика
// комнаты" (лейбла не было и не должно быть)
export function shiftPendingRollLabel() {
  return pending.length > 0 ? pending.shift() : null;
}
