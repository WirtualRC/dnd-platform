// Общий хелпер для крит-эмодзи на d20-бросках (проверки/спасброски/атаки) —
// используется и локальным путём (roll.js), и сокет-подтверждением брoска
// в комнате (useRoomStore.js), поэтому вынесен в отдельный модуль без
// зависимостей, чтобы не устраивать циклический импорт между ними.
// 🔥 на натуральной 20 (критический успех), 🩸 на натуральной 1
// (критическая неудача) — как и в 5e, это именно про саму кость, не про
// итоговый total с модификаторами.
export function wrapCritLabel(label, total, natural) {
  if (natural === 20) return `🔥 ${label} — ${total} 🔥`;
  if (natural === 1) return `🩸 ${label} — ${total} 🩸`;
  return label;
}
